export function fmtStars(n: number) {
  return n >= 1000 ? `${(n / 1000).toFixed(n >= 10_000 ? 0 : 1)}k` : String(n);
}

export function scoreColor(s: number) {
  return s >= 70 ? "var(--good)" : s >= 45 ? "var(--warn)" : "var(--bad)";
}
